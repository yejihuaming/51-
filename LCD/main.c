//延时函数
void delay(int xms)	
{
	int i,j;
	for(i=0;i<xms;i++){
		for(j=0;j<120;j++);
	}
}

//写入指令函数
void writecom(char com)
{
	RS = 0;
	RW = 0;
	E = 0;
	P2 = com;
	E = 1;
	delay(5);
	E = 0;
}

//写入数据函数
void writedat(char dat)
{
	RS = 1;
	RW = 0;
	E = 0;
	P2 = dat;
	E = 1;
	_nop_();
	_nop_();
	E = 0;
}

//选框（8*8），从上往下
void set_page(uint8 page)
{
	page = 0XB8 | page;
	writecom(page);
}

//选行数
void set_line(uint8 startline)
{
	startline = 0XC0 | startline;
	writecom(startline);
}

//选列数
void set_column(uint8 column)
{
	column = 0X3F & column;
	column = 0X40 | column;
	writecom(column);
}

//开关函数
void setonoff(uint8 onoff)
{
	onoff = 0X3E | onoff;
	writecom(onoff);
}

//选择左右屏
void selectscreen(uint8 screen)
{
	switch(screen)
	{
		case 0:CS1 = 0;CS2 = 0;break;
		case 1:CS1 = 0;CS2 = 1;break;
		case 2:CS1 = 1;CS2 = 0;break;
		default: break;
	}
}

//清屏函数
void clearscreen(uint8 screen)
{
	uint8 i,j;
	selectscreen(screen);
	for(i = 0;i<8;i++)
	{
		set_page(i);
		set_column(0);
		for(j = 0;j<64;j++)
		{
			writedat(0X00);
		}
	}
}

//演示汉字函数（16*16）
void display_ch(uint8 screen,uint8 page,uint8 column,uint8 *p)
{
	uint8 i;
	selectscreen(screen);
	
	set_page(page);
	set_column(column);
	for(i = 0;i<16;i++)
	{
		writedat(p[i]);
	}
	
	set_page(page+1);
	set_column(column);
	for(i = 0;i<16;i++)
	{
		writedat(p[i+16]);
	}
}

//显示图片函数（）64*64
void display_im(uint8 screen,uint8 page,uint8 column,uint8 *p)
{
	uint8 i;
	uint8 a; 
	selectscreen(screen);
	for(a = 0;a<8;a++)
	{
		set_page(page+a);
		set_column(column);
		for(i = 0;i<64;i++)
		{
			writedat(p[i+a*64]);
		}
	}
}

